/**
 * Recorrido REAL desde que el usuario queda logueado hasta que la primera pantalla está pintada.
 *
 * Es el tramo que suele estar sin documentar y es el que más llamadas encadena: abrir sesión,
 * resolver quién es, decidir si va a la pantalla principal o a terminar su onboarding, y traer los
 * datos que esa pantalla muestra. Cada `routePath` existe hoy en `src/modules/`; el informe de
 * consistencia marca como error cualquiera que no exista.
 */

import type { WorkflowSeed, WorkflowStageSeed, WorkflowStepSeed } from './customer-credit-workflow.seed-data.js';

