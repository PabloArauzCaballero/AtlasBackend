/**
 * Árbol REAL del recorrido estándar de Atlas: registro -> onboarding -> revisión -> habilitación ->
 * crédito, expresado como etapas, subetapas, pasos, dependencias y transiciones.
 *
 * Cada `routePath` de este archivo corresponde a un endpoint que EXISTE hoy en `src/modules/`. No se
 * inventó ninguno: el informe de consistencia (`GET /operations/workflows/:code/consistency`) compara
 * esta definición contra las rutas que el proceso tiene montadas y marca como error cualquier paso
 * que no exista. Los roles son los del decorador `@Roles(...)` de cada handler; los estados son los
 * de `customer-lifecycle.constants.ts`; los códigos de bloqueo, los de
 * `customer-eligibility.constants.ts`. Esa es la trazabilidad que hace útil al catálogo: si alguna
 * de esas tres fuentes cambia y este archivo no, el informe lo dice.
 *
 * Las reglas de completitud (`completionRule`) NO reimplementan el cálculo de avance: nombran la
 * sección, el estado o los bloqueadores que ya produce `CustomerEligibilityService`. Una etapa sin
 * señal automática se declara `manual` y se reporta como `not_applicable`, en vez de fingir que el
 * sistema sabe si un analista ya la resolvió.
 */

