const READ_RETRY = { strategy: 'safe_retry', maxAttempts: 3, backoff: 'exponential' };
const IDEMPOTENT_RETRY = { strategy: 'client_retry_with_idempotency_key', maxAttempts: 3, backoff: 'exponential' };
const NO_RETRY = { strategy: 'no_retry', reason: 'Comando no idempotente: reintentar puede duplicar el efecto.' };

function step(seed: WorkflowStepSeed): WorkflowStepSeed {
  return seed;
}

