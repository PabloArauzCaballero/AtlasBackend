export type WorkflowStepSeed = {
  stepCode: string;
  name: string;
  description: string;
  httpMethod: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
  routePath: string;
  executionOrder: number;
  isMandatory?: boolean;
  isRepeatable?: boolean;
  requiresIdempotencyKey?: boolean;
  requiresAuth?: boolean;
  isFlowEntry?: boolean;
  isFlowExit?: boolean;
  allowedRoles: string[];
  requiredStates?: string[];
  resultingStates?: string[];
  inputContract?: Record<string, unknown>;
  outputContract?: Record<string, unknown>;
  validationRules?: string[];
  possibleErrors?: string[];
  retryStrategy?: Record<string, unknown>;
  producesEvents?: string[];
  consumesEvents?: string[];
  successCriteria?: Record<string, unknown>;
  failureCriteria?: Record<string, unknown>;
};

export type WorkflowStageSeed = {
  stageCode: string;
  name: string;
  description: string;
  moduleCode: string;
  actorType: 'customer' | 'internal_user' | 'system' | 'external_provider';
  displayOrder: number;
  isOptional?: boolean;
  isEntryStage?: boolean;
  isTerminalStage?: boolean;
  allowedRoles?: string[];
  requiredStates?: string[];
  resultingStates?: string[];
  completionRule: Record<string, unknown>;
  steps: WorkflowStepSeed[];
  subStages?: WorkflowStageSeed[];
};

export type WorkflowDependencySeed = {
  stepCode: string;
  dependsOnStepCode: string;
  dependencyType: 'requires_completion' | 'requires_data' | 'soft';
  description: string;
};

export type WorkflowTransitionSeed = {
  transitionCode: string;
  fromStepCode: string | null;
  toStepCode: string | null;
  conditionType: 'always' | 'on_success' | 'on_error' | 'on_state' | 'conditional';
  conditionExpression?: Record<string, unknown>;
  description: string;
  displayOrder: number;
  isDefaultPath?: boolean;
};

